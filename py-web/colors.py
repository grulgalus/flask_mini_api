class colors():
    def red(s):
        print(f"\033[31m{s}\033[0m")
    def green(s):
        print(f"\033[32m{s}\033[0m")
    def yellow(s):
        print(f"\033[33m{s}\033[0m")
    def blue(s):
        print(f"\033[34m{s}\033[0m")
    def cyan(s):
        print(f"\033[36m{s}\033[0m")
    def bold(s):
        print(f"\033[1m{s}\033[0m")
    def pink(s):
        print(f"\033[95m{s}\033[0m")
